"""Bounded advisory request interpreter with an offline scripted transport."""
from __future__ import annotations

import copy
import json
from pathlib import Path
import time
from typing import Any, Protocol

from workflow_sentinel.cli import investigate
from workflow_sentinel.validation import validate

MAX_TURNS = 8
MAX_RESPONSE_BYTES = 4096
MAX_OBSERVATION_BYTES = 64000
MAX_SECONDS = 65.0


def decode(raw: bytes) -> Any:
    """Decode script JSON without silently accepting duplicate object fields."""
    def fields(pairs: list[tuple[str, Any]]) -> dict[str, Any]:
        value: dict[str, Any] = {}
        for key, item in pairs:
            if key in value:
                raise ValueError('Duplicate response field')
            value[key] = item
        return value
    return json.loads(raw, object_pairs_hook=fields)


def request(value: Any, packet_count: int) -> dict[str, Any]:
    """Validate the complete response; reject unknown fields and boolean indices."""
    if not isinstance(value, dict) or len(json.dumps(value).encode()) > MAX_RESPONSE_BYTES:
        raise ValueError('response shape or size')
    action = value.get('action')
    if action == 'abstain' and set(value) == {'action'}:
        return value
    if action not in {'evidence', 'propose', 'validate', 'finish'}:
        raise ValueError('unknown action')
    if set(value) != {'action', 'packet'} or type(value['packet']) is not int:
        raise ValueError('response fields')
    if not 0 <= value['packet'] < packet_count:
        raise ValueError('packet range')
    return value


class Adapter(Protocol):
    mode: str

    def next(self, packets: list[dict[str, Any]], observations: list[dict[str, Any]],
             remaining: float) -> Any: ...


def run(sarif: dict[str, Any], root: Path, responses: Any,
        scanner: Path | None = None, *, adapter: Adapter | None = None) -> dict[str, Any]:
    """Interpret scripted responses or an explicitly injected trusted provider adapter.

    Evidence tools can select only packets already resolved by the bounded investigator.
    Proposals are generated by deterministic policy, never supplied as model patch text.
    Scanner requests require an explicitly supplied scanner and share a two-pair budget.
    """
    baseline = investigate(sarif, root, preview_repairs=True)
    result: dict[str, Any] = {
        'schema_version': 'agent-1.0',
        'mode': adapter.mode if adapter else 'offline-scripted-advisory',
        'decision': 'abstain', 'reason': 'No completed request sequence',
        'report': baseline, 'observations': [], 'trace': [],
        'limits': {'turns': MAX_TURNS, 'response_bytes': MAX_RESPONSE_BYTES,
                   'observation_bytes': MAX_OBSERVATION_BYTES, 'seconds': MAX_SECONDS,
                   'validation_pairs': 2},
    }
    if adapter is None and (not isinstance(responses, list)
                            or not 1 <= len(responses) <= MAX_TURNS):
        result['reason'] = 'Response sequence must contain 1 to 8 turns'
        return result
    start = time.monotonic()
    seen: set[int] = set()
    proposed: set[int] = set()
    checked: set[int] = set()
    validations = 0
    packets = baseline['packets']
    for turn in range(MAX_TURNS if adapter else len(responses)):
        if time.monotonic() - start >= MAX_SECONDS:
            result['reason'] = 'Session deadline exhausted'
            return result
        if adapter:
            try:
                response = adapter.next(packets, copy.deepcopy(result['observations']),
                                        MAX_SECONDS - (time.monotonic() - start))
            except Exception:
                result['trace'].append({'turn': turn, 'status': 'adapter-error'})
                result['reason'] = 'Provider refused, failed or exceeded protocol/deadline bounds'
                return result
        else:
            response = responses[turn]
        if time.monotonic() - start >= MAX_SECONDS:
            result['reason'] = 'Session deadline exhausted'
            return result
        try:
            command = request(response, len(packets))
        except (ValueError, TypeError, RecursionError):
            result['trace'].append({'turn': turn, 'status': 'invalid-response'})
            result['reason'] = 'Invalid structured response'
            return result
        action = command['action']
        result['trace'].append({'turn': turn, 'action': action})
        if adapter is None and action in {'abstain', 'finish'} and turn != len(responses) - 1:
            result['reason'] = 'Terminal response must be last'
            return result
        if action == 'abstain':
            result['reason'] = 'Adapter abstained'
            return result
        index = command['packet']
        packet = packets[index]
        observation: dict[str, Any] = {'packet': index, 'action': action}
        if action == 'evidence':
            observation['evidence'] = copy.deepcopy(packet['evidence'])
            observation['decision'] = packet['decision']
            seen.add(index)
        elif action == 'propose':
            if index not in seen:
                result['reason'] = 'Proposal requires prior evidence request'
                return result
            observation['repair'] = copy.deepcopy(packet['repair'])
            if packet['repair']['status'] == 'proposed':
                proposed.add(index)
        elif action == 'validate':
            if index not in proposed or index in checked or validations >= 2:
                result['reason'] = 'Validation prerequisite or budget refused'
                return result
            if scanner is None:
                result['reason'] = 'Validation requires explicit scanner opt-in'
                return result
            validations += 1
            checked.add(index)
            observation['static_validation'] = validate(packet, root, scanner)
            packet['static_validation'] = observation['static_validation']
        elif action == 'finish':
            if index not in seen:
                result['reason'] = 'Completion requires prior evidence request'
                return result
            if index in proposed and packet.get('static_validation', {}).get('status') != 'validated':
                result['reason'] = 'Proposed repair lacks successful static validation'
                return result
            result['decision'] = 'review' if packet['decision'] == 'review' else 'abstain'
            result['reason'] = 'Advisory selection; deterministic packet governs outcome'
            result['selected_packet'] = index
            return result
        if len(json.dumps(result['observations'] + [observation]).encode()) > MAX_OBSERVATION_BYTES:
            result['reason'] = 'Observation budget exhausted'
            return result
        result['observations'].append(observation)
    return result
